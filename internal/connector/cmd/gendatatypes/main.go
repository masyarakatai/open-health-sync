// Command gendatatypes rewrites the machine-readable data types section of
// docs/connectors/README.md between its generated markers from what each
// registered connector declares in DataTypes. The section is generated so it
// cannot drift; a test fails when the committed copy differs from this
// output.
//
// Run it from the repository root:
//
//	go run ./internal/connector/cmd/gendatatypes
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	_ "github.com/soma-intelligence/open-health-sync/connectors/all"
	"github.com/soma-intelligence/open-health-sync/internal/connector"
)

// Markers bracket the generated section of the README. Everything between
// them, the markers included, belongs to this command.
const (
	startMark = "<!-- data-types:generated:start -->"
	endMark   = "<!-- data-types:generated:end -->"
)

func main() {
	readme := flag.String("readme", "docs/connectors/README.md", "file to splice the generated section into")
	flag.Parse()

	want, err := Block()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gendatatypes:", err)
		os.Exit(1)
	}
	doc, err := os.ReadFile(*readme)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gendatatypes:", err)
		os.Exit(1)
	}
	got, err := Splice(doc, want)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gendatatypes:", err)
		os.Exit(1)
	}
	if bytes.Equal(got, doc) {
		return
	}
	if err := os.WriteFile(*readme, got, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gendatatypes:", err)
		os.Exit(1)
	}
}

// Block renders the generated section: the section heading, why the values
// are what they are, and one table row per registered connector, sorted by
// slug, markers included.
func Block() ([]byte, error) {
	type row struct {
		slug  string
		kinds []string
		rest  []string
	}
	var rows []row
	for _, c := range connector.All() {
		dt, ok := connector.AsDataTypes(c)
		if !ok {
			return nil, fmt.Errorf("%s declares no data types", c.Slug())
		}
		r := row{slug: c.Slug()}
		for _, v := range dt.DataTypes() {
			if isKind(v) {
				r.kinds = append(r.kinds, v)
			} else {
				r.rest = append(r.rest, v)
			}
		}
		if len(r.kinds) == 0 {
			return nil, fmt.Errorf("%s names no record kind", c.Slug())
		}
		rows = append(rows, r)
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].slug < rows[j].slug })

	var b strings.Builder
	b.WriteString(startMark + "\n")
	b.WriteString(`## Machine-readable data types

` + "`GET /v1/providers`" + ` returns ` + "`data_types`" + ` for every enabled
connector: the record kinds it writes and, beside them, the canonical quantity
names it delivers (for example ` + "`heart_rate`" + `), so an app can show that a
source gives sleep and heart rate, not workouts, without reading the
connector's docs. Kinds are the ` + "`connector.Kind`" + ` constants; quantity
names come from the canonical vocabulary in [../data-model.md](../data-model.md).
This section is generated by ` + "`go run ./internal/connector/cmd/gendatatypes`" + `;
a test fails when it differs.

| Connector | Record kinds | Quantity names |
|---|---|---|
`)
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n",
			r.slug, codeList(r.kinds), codeList(r.rest))
	}
	b.WriteString(endMark)
	return []byte(b.String()), nil
}

// Splice returns doc with everything between the markers (inclusive)
// replaced by block.
func Splice(doc, block []byte) ([]byte, error) {
	s := string(doc)
	i := strings.Index(s, startMark)
	j := strings.Index(s, endMark)
	if i < 0 {
		return nil, fmt.Errorf("no %s marker found", startMark)
	}
	if j < i {
		return nil, fmt.Errorf("%s precedes %s", endMark, startMark)
	}
	var out strings.Builder
	out.WriteString(s[:i])
	out.Write(block)
	out.WriteString(s[j+len(endMark):])
	return []byte(out.String()), nil
}

// codeList renders names as inline code joined by commas, empty when there
// are none.
func codeList(names []string) string {
	parts := make([]string, len(names))
	for i, n := range names {
		parts[i] = "`" + n + "`"
	}
	return strings.Join(parts, ", ")
}

// isKind reports whether v is one of the connector.Kind constants.
func isKind(v string) bool {
	switch v {
	case connector.KindSample, connector.KindCategory, connector.KindSleep,
		connector.KindWorkout, connector.KindRoute, connector.KindNutrition,
		connector.KindECG, connector.KindHeartbeat, connector.KindDaily,
		connector.KindObservation:
		return true
	}
	return false
}
